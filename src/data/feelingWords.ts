/**
 * 找出用户这一句里选用的情绪词。
 * 只取最长的几个，避免「累」把「疲惫」压掉之后又重复给出一堆近义词。
 */
export function findFeelingWords(text: string): string[] {
  const hits = FEELING_WORDS.filter((word) => text.includes(word));
  return [...new Set(hits)].sort((a, b) => b.length - a.length).slice(0, 4);
}
