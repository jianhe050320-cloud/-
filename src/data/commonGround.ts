/**
 * 渲染成给模型看的紧凑文本。
 * 只给场景和常见感受，不给任何「结论」——结论必须由模型在对话里自己长出来。
 */
export function renderCommonGround(limit = 14): string {
  return COMMON_GROUND.slice(0, limit)
    .map((item) => `- ${item.scene}｜常见的感受：${item.feelings.join('、')}`)
    .join('\n');
}
