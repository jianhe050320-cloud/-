/**
 * 共通经历素材库。
 *
 * 存在的理由：采访者如果只能「针对用户刚说的那句」提问，就会显得又冷又笨。
 * 有一层「我知道这一类经历大概是什么样」的储备，才可能说出
 * 「我听说很多人在那段时间都会有这种感觉」——这才是共鸣，而不是复读。
 *
 * ⚠️ 红线（必须同时写进 prompt，见 COMMON_GROUND_RULES）：
 *   1. 不许假装自己有经历（不要说「我也经历过」「我懂那种感觉」，AI 没有人生的资格）。
 *   2. 不许用素材给用户下定义（不要说「所以你是一个敏感的人」）。
 *   3. 素材只能是「猜想 + 邀请确认」，且必须让用户有否认的余地。
 *   4. 素材只是备选，优先仍然跟着用户自己说的走；不要为了用素材而硬扯。
 */

export interface CommonGroundItem {
  id: string;
  /** 场景 */
  scene: string;
  /** 这一类经历里常见的感受（用来表达理解，不是用来断定用户） */
  feelings: string[];
}

