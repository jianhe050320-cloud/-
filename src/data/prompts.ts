/** 把结构化 Memory 压成一段给模型的简要上下文（控制 token） */
export function renderMemoryDigest(memory: StoryMemory): string {
  const lines: string[] = [];
  if (memory.story_title) lines.push(`故事标题（暂定）：${memory.story_title}`);
  if (memory.people.length) {
    lines.push(
      `人物：${memory.people
        .map((person) => `${person.name}（${person.relationship || '关系未知'}，重要度${person.importance}）`)
        .join('、')}`,
    );
  }
  if (memory.events.length) {
    lines.push(`事件：${memory.events.map((event) => event.description).filter(Boolean).join('；')}`);
  }
  if (memory.turning_points.length) {
    lines.push(
      `转折：${memory.turning_points
        .map((point) => `${point.before || '?'} → ${point.after || '?'}${point.trigger ? `（因为${point.trigger}）` : ''}`)
        .join('；')}`,
    );
  }
  if (memory.emotions.length) {
    lines.push(`情绪：${memory.emotions.map((emotion) => emotion.emotion).filter(Boolean).join('、')}`);
  }
  if (memory.details.length) {
    lines.push(`细节：${memory.details.map((detail) => detail.detail).filter(Boolean).join('；')}`);
  }
  const pending = memory.meaning.filter((item) => !item.confirmed_by_user);
  if (pending.length) {
    lines.push(`尚未被用户确认的理解（只能邀请确认，不能当成事实）：${pending.map((item) => item.interpretation).join('；')}`);
  }
  if (memory.open_threads.length) {
    lines.push(`还没讲完的线头：${memory.open_threads.join('；')}`);
  }
  if (memory.user_quotes.length) {
    lines.push(`用户原话（保持这些措辞）：${memory.user_quotes.slice(-6).join(' ｜ ')}`);
  }
  return lines.length ? lines.join('\n') : '（目前还什么都没有，用户刚开口。）';
}

/** 把最近对话渲染成纯文本，供理解器阅读 */
export function renderTranscript(
  messages: { role: 'user' | 'assistant'; text: string }[],
  limit = 16,
): string {
  const recent = messages.slice(-limit);
  if (!recent.length) return '（还没有任何对话）';
  return recent
    .map((message) => `${message.role === 'user' ? '用户' : '采访者'}：${message.text}`)
    .join('\n');
}
